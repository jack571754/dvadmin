import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';

const prototype = pathToFileURL(resolve('../docs/prototypes/dvadmin.html')).href;
test('redesigned prototype: member views, filtering, recovery, guarded permissions and themes', async ({ page }, testInfo) => {
  await mkdir('quality-reports', { recursive: true });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto(prototype);
  await expect(page.getByRole('heading', { name: '用户管理', exact: true })).toBeVisible();
  await expect(page.locator('#userRows tr')).toHaveCount(8);
  await page.screenshot({ path: 'quality-reports/design-v2-users.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('tab', { name: '待激活' }).click();
  await expect(page.locator('#userRows tr')).toHaveCount(1);
  await page.getByRole('tab', { name: '所有成员' }).click();
  await page.getByRole('textbox', { name: '搜索用户', exact: true }).fill('林远');
  await expect(page.locator('#userRows tr')).toHaveCount(1);
  await page.getByLabel('预览状态').click();
  await page.getByLabel('列表状态').selectOption('error');
  await expect(page.getByRole('heading', { name: '暂时无法加载成员' })).toBeVisible();
  await page.getByRole('button', { name: '重新加载', exact: true }).click();
  await expect(page.getByRole('textbox', { name: '搜索用户', exact: true })).toHaveValue('林远');
  await page.getByLabel('预览状态').click();
  await page.locator('nav').getByRole('button', { name: '角色与权限' }).click();
  await page.getByRole('button', { name: '配置角色权限', exact: true }).click();
  await page.getByRole('tab', { name: '字段权限', exact: true }).click();
  await page.getByRole('checkbox', { name: '手机号查询权限' }).uncheck();
  await page.evaluate(() => { (document.getElementById('saveScenario') as HTMLSelectElement).value = 'error'; });
  await page.getByRole('button', { name: '保存字段权限' }).click();
  await expect(page.getByRole('alert')).toHaveText('保存失败，修改仍保留，请重试。');
  await page.evaluate(() => { (document.getElementById('saveScenario') as HTMLSelectElement).value = 'normal'; });
  await page.getByRole('button', { name: '保存字段权限' }).click();
  await expect(page.locator('#fieldState')).toHaveText('所有更改已保存');
  await page.screenshot({ path: 'quality-reports/design-v2-permissions.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('checkbox', { name: '姓名查询权限' }).uncheck();
  await page.getByRole('button', { name: '关闭权限配置' }).click();
  await expect(page.getByRole('heading', { name: '有未保存的更改' })).toBeVisible();
  await page.getByRole('button', { name: '继续编辑' }).click();
  await expect(page.locator('#permissionDrawer')).toBeVisible();
  await page.getByRole('button', { name: '关闭权限配置' }).click();
  await page.getByRole('button', { name: '放弃更改' }).click();
  await page.getByRole('button', { name: '配置角色权限', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: '姓名查询权限' })).toBeChecked();
  await page.getByRole('button', { name: '关闭权限配置' }).click();
  await page.locator('nav').getByRole('button', { name: '工作台' }).click();
  await page.screenshot({ path: 'quality-reports/design-v2-home.png', fullPage: false, animations: 'disabled' });
  await page.getByRole('button', { name: '切换深色模式' }).click();
  await expect(page.locator('body')).toHaveClass('dark');
  await page.screenshot({ path: 'quality-reports/design-v2-dark.png', fullPage: false, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({ path: 'quality-reports/design-v2-mobile.png', fullPage: false, animations: 'disabled' });
  await testInfo.attach('design-v2', { body: await page.screenshot(), contentType: 'image/png' });
});

test('member editor and command search are functional', async ({ page }) => {
  await page.goto(prototype);
  await page.getByRole('button', { name: '新建用户', exact: true }).click();
  await page.locator('#userName').fill('测试成员');
  await page.locator('#userEmail').fill('new@example.com');
  await page.getByRole('button', { name: '保存用户', exact: true }).click();
  await expect(page.locator('#userRows tr')).toHaveCount(9);
  await page.getByRole('button', { name: '搜索功能', exact: false }).click();
  await page.locator('#commandQuery').fill('角色');
  await page.locator('#commandResults button').click();
  await expect(page.getByRole('heading', { name: '角色与权限', exact: true })).toBeVisible();
});
